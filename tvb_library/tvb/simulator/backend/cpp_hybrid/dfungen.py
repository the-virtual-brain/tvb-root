def _main(argv=None) -> int:
    import argparse
    parser = argparse.ArgumentParser(
        prog="python -m tvb.simulator.backend.cpp_hybrid.dfungen",
        description="Emit the expression-driven C++ dfun source used by the "
                    "cpp_hybrid backend (no compilation).")
    parser.add_argument("--emit", required=True, metavar="PATH",
                        help="write the generated C++ source to PATH")
    parser.add_argument("--meta", metavar="PATH",
                        help="write the model metadata as JSON to PATH")
    parser.add_argument("--entry-name", default="cph_generic_dfun",
                        help='name of the emitted extern "C" entry symbol '
                             '(the prebuilt extension uses cph_builtin_dfun)')
    parser.add_argument("--strict", action="store_true",
                        help="fail if a model module cannot be imported or an "
                             "expression-driven model cannot be configured or "
                             "emitted, instead of skipping it")
    args = parser.parse_args(argv)
    try:
        src, meta = emit_sources(strict=args.strict, entry_name=args.entry_name)
        emit_path = Path(args.emit)
        emit_path.parent.mkdir(parents=True, exist_ok=True)
        emit_path.write_text(src)
        if args.meta:
            meta_path = Path(args.meta)
            meta_path.parent.mkdir(parents=True, exist_ok=True)
            meta_path.write_text(json.dumps(meta, indent=2, sort_keys=True)
                                 + "\n")
    except Exception as exc:
        print(f"dfungen: {exc}", file=sys.stderr)
        return 1
    print(f"dfungen: emitted {len(meta)} dfun(s), ids "
          f"{_FIRST_MODEL_ID}..{_FIRST_MODEL_ID + len(meta) - 1} -> {emit_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())

#: first id of the generated (expression-driven) dispatch range; the emitted
#: dispatcher maps model_id -> table index as (model_id - _FIRST_MODEL_ID), so
#: ids and the table must stay in lockstep
_FIRST_MODEL_ID = 100


class DfunGenerationError(RuntimeError):
    """Strict-mode failure: a model that should have produced a generated dfun
    did not.  Raised only when ``strict=True`` (the build-time path), where
    silently skipping a model would shrink model coverage unnoticed."""


def _exc_text(exc: BaseException) -> str:
    return f"{type(exc).__name__}: {exc}"


def _declares_dfuns(cls) -> bool:
    """Whether a Model subclass declares ``state_variable_dfuns`` in a class
    body (as a neotraits ``Final`` trait or as a plain dict), i.e. it is meant
    to be expression-driven.  Models that do not (the numba-only Zerlaut and
    CerebellarMF kernels) are not generic-dfun candidates and must not be
    reported as strict-mode failures."""
    return any("state_variable_dfuns" in vars(c) for c in cls.__mro__)


def _failure_report(failures) -> str:
    """Aggregate strict-mode failures into one message; each offender is one
    ``module.Class: <stage> <exception text>`` line."""
    counts = {}
    for _, stage, _ in failures:
        counts[stage] = counts.get(stage, 0) + 1
    summary = ", ".join(f"{n} {stage} failure(s)"
                        for stage, n in sorted(counts.items()))
    detail = "\n".join(f"  {name}: {stage} {text}"
                       for name, stage, text in failures)
    return (f"strict dfun generation failed ({summary}); every offender is "
            f"listed below:\n{detail}")


def _collect_models():
    """Discover expression-driven models.

    Returns ``(models, failures)``: ``models`` maps model class name to a
    configured instance, ``failures`` lists ``(qualified_name, stage,
    exception_text)`` for model modules that could not be imported and concrete
    ``state_variable_dfuns`` classes that could not be instantiated/configured.
    Abstract scaffolding (``ModelNumbaDfun``, ``ReducedSetBase``) is skipped: it
    is not a model, so its absence is not a coverage loss.  Failures are always
    collected and never raised here; callers decide whether to report them
    (``collect_models``/``emit_sources`` with ``strict=True``) or ignore them.
    """
    import pkgutil
    from tvb.simulator.models.base import Model
    import tvb.simulator.models as pkg

    models = {}
    failures = []
    mods = []
    if hasattr(pkg, '__path__'):
        for mi in pkgutil.iter_modules(pkg.__path__):
            mod_name = f"tvb.simulator.models.{mi.name}"
            try:
                mods.append(importlib.import_module(mod_name))
            except Exception as exc:
                failures.append((mod_name, "import", _exc_text(exc)))
    else:
        mods = [getattr(pkg, m) for m in dir(pkg)
                if inspect.ismodule(getattr(pkg, m))]

    seen = set()
    for mod in mods:
        for cn in dir(mod):
            cls = getattr(mod, cn)
            if not (isinstance(cls, type) and issubclass(cls, Model)
                    and cls is not Model):
                continue
            if cls in seen or cn in models:
                continue
            seen.add(cls)
            if inspect.isabstract(cls):
                continue
            generic_candidate = _declares_dfuns(cls)
            try:
                o = cls()
                o.configure()
            except Exception as exc:
                if generic_candidate:
                    failures.append((f"{cls.__module__}.{cls.__name__}",
                                     "configure", _exc_text(exc)))
                continue
            svd = getattr(o, "state_variable_dfuns", None)
            if isinstance(svd, dict) and svd:
                models[cn] = o
    return models, failures


def collect_models(strict: bool = False):
    """Map model class name -> configured instance for all expression-driven
    models (those declaring state_variable_dfuns).

    ``strict=False`` (the runtime default) keeps today's lenient behaviour and
    silently skips what cannot be built; ``strict=True`` raises
    ``DfunGenerationError`` listing every failure instead.
    """
    models, failures = _collect_models()
    if strict and failures:
        raise DfunGenerationError(_failure_report(failures))
    return models


